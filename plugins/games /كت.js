const shuffle = arr => {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
};

const QUESTIONS = [...new Set([
  ...EXTRA,
  ...TOPICS.flatMap(topic => FORMS.map(make => make(topic)))
])];

const handler = async (m, { conn }) => {
  const chat = m.chat;
  if (!global.ketQuestions) global.ketQuestions = {};
  let state = global.ketQuestions[chat];

  if (!state || !state.deck || state.deck.length === 0) {
    const previous = state?.last || '';
    const deck = shuffle(QUESTIONS);
    if (deck.length > 1 && deck[deck.length - 1] === previous) {
      [deck[0], deck[deck.length - 1]] = [deck[deck.length - 1], deck[0]];
    }
    state = global.ketQuestions[chat] = { deck, last: previous };
  }

  const question = state.deck.pop();
  state.last = question;

  await conn.sendMessage(chat, {
    text: `╭━━━〔 🍷 𝑴𝑨𝑿 𝑩𝑶𝑻 〕━━━╮\n\n🎭 *ســؤال كــت*\n\n❖ ${question}\n\n╰━━━━━━━━━━━━━━━━╯`
  }, { quoted: m });
};

handler.help = ['كت'];
handler.tags = ['games'];
handler.command = /^(كت|ket)$/i;

export default handler;
