let lastReplies = new Map();

// ═══════════ Handler الرئيسي ═══════════
handler.before = async function (m, { conn, isOwner, isROwner }) {
  // 1. التحقق من وجود نص
  if (!m.text) return false;

  let txt = m.text.trim();

  // 2. البحث عن المطابقة وإرسال الرد
  for (let item of triggers) {
    try {
      if (item.pattern.test(txt)) {
        let choices = [...item.replies];
      if (item.developerReplies && isROwner) {
        choices.push(...item.developerReplies);
      }
      const key = item.key || item.pattern.toString();
      const previous = lastReplies.get(key);
      let available = choices.filter(reply => reply !== previous);
      if (!available.length) available = choices;
      let ranReply = available[Math.floor(Math.random() * available.length)];
      lastReplies.set(key, ranReply);
        await m.reply(ranReply);
        return true;
      }
    } catch (e) {
      console.error('[꧁༒☬ 𝑴𝑨𝑿 𝑩𝑶𝑻 ☬༒꧂-Triggers] خطأ في الـ pattern:', e?.message);
    }
  }

  return false;
};

